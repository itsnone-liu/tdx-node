#!/usr/bin/env python3
"""LHB (龙虎榜) official-source backfill, 2021-01-01 -> today. Data type ①.

Sources (both free & official):
  SSE  main board : query.sse.com.cn/marketdata/tradedata/queryAllTradeOpenDate.do
                    ONE call per day; every row = (stock, reason) with BOTH
                    branchNameB/branchTxAmtB and branchNameS/branchTxAmtS
                    comma-joined top-5 seat lists inline. Amounts in yuan.
  SSE  STAR board : queryKCBTradeInfo.do  (tradeDate, flag=2) — same day-call;
                    rows carry deptNameB/deptTxAmtB or deptNameS/deptTxAmtS
                    comma-joined top-5. Amounts in 10k-yuan (万元).
  SZSE            : www.szse.cn/api/report/ShowReport/data
                    daily list   : CATALOGID=1842_xxpl_after TABKEY=tab1
                                   txtStart=txtEnd=YYYY-MM-DD, PAGENO=1..N
                    seat details : CATALOGID=1842_detal TABKEY=tab1,tab2
                                   DQRQ/ZQDM/ZBDM from the row's bz link.
                                   tab2 rows: mmlb(买1..卖5) zsmc mrje mcje (yuan).

Raw responses are archived verbatim under lhb/raw/**; per-day status lives in
lhb/backfill_state.json (resume-safe: COMPLETE days are skipped on rerun).

Usage:
  python lhb_backfill.py --dates 20210105,20210106      # explicit days
  python lhb_backfill.py --from 20210101 --to 20210131  # calendar range
  python lhb_backfill.py                                # full backfill
"""
from __future__ import annotations
import argparse
import json
import random
import re
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from net_common import ThrottledClient, qs  # noqa: E402

NODE = Path(r'D:\tdx-node')
LHB = NODE / 'lhb'
RAW = LHB / 'raw'
STATE_FP = LHB / 'backfill_state.json'
CAL_FP = NODE / 'manifests' / 'trading_calendar_2021_2026.json'
PREFILL_FP = NODE / 'manifests' / 'calendar_prefill_2021.json'

SSE_Q = 'http://query.sse.com.cn/marketdata/tradedata/'
SSE_HEADERS = {'Referer': 'http://www.sse.com.cn/'}
SZSE_API = 'https://www.szse.cn/api/report/ShowReport/data'
SZSE_HEADERS = {'Referer': 'https://www.szse.cn/disclosure/tradepublic/day.html'}

sse_cli = ThrottledClient(min_interval_s=0.22)
szse_cli = ThrottledClient(min_interval_s=0.35, max_retries=8,
                            breaker_threshold=3, cooldown_s=150.0)


# ---------------------------------------------------------------- calendar
def load_calendar() -> list[str]:
    """Trading days as YYYYMMDD. TDX local calendar starts 20210802; the
    2021-01..2021-07 gap is filled from calendar_prefill_2021.json if present
    (generated by prefetch_calendar.py from SSE-index daily klines)."""
    days = set()
    if CAL_FP.exists():
        days.update(json.loads(CAL_FP.read_text(encoding='utf-8')))
    if PREFILL_FP.exists():
        days.update(json.loads(PREFILL_FP.read_text(encoding='utf-8')))
    return sorted(days)


def load_state() -> dict:
    if STATE_FP.exists():
        return json.loads(STATE_FP.read_text(encoding='utf-8'))
    return {}


def save_state(state: dict):
    """Merge-safe: reload the on-disk state first so concurrent runs of this
    script never clobber each other's day entries, then overlay in-memory
    records and atomically replace."""
    merged: dict = {}
    try:
        if STATE_FP.exists():
            merged.update(json.loads(STATE_FP.read_text(encoding='utf-8')))
    except (json.JSONDecodeError, OSError):
        pass
    merged.update(state)
    tmp = STATE_FP.with_suffix('.tmp')
    tmp.write_text(json.dumps(merged, ensure_ascii=False, indent=1),
                   encoding='utf-8')
    tmp.replace(STATE_FP)
    state.clear()
    state.update(merged)


def save_raw(rel: str, obj) -> str:
    fp = RAW / rel
    fp.parent.mkdir(parents=True, exist_ok=True)
    if fp.exists():
        return rel  # already archived verbatim — never overwrite raw evidence
    fp.write_text(json.dumps(obj, ensure_ascii=False), encoding='utf-8')
    return rel


# ---------------------------------------------------------------- fetchers
def fetch_sse_main(day: str) -> list[dict]:
    url = (SSE_Q + 'queryAllTradeOpenDate.do?' +
           qs({'token': 'QUERY', 'tradeDate': day, 'flag': '1'}))
    obj = sse_cli.get_json(url, extra_headers=SSE_HEADERS)
    save_raw(f'sse_main/{day}.json', obj)
    return (obj.get('pageHelp') or {}).get('data') or []


def fetch_sse_star(day: str) -> list[dict]:
    url = SSE_Q + 'queryKCBTradeInfo.do?' + qs({'tradeDate': day, 'flag': '2'})
    obj = sse_cli.get_json(url, extra_headers=SSE_HEADERS)
    save_raw(f'sse_star/{day}.json', obj)
    return (obj.get('pageHelp') or {}).get('data') or []


def fetch_szse_list(day: str) -> list[dict]:
    """All pages of the SZSE daily LHB list. Returns rows."""
    iso = f'{day[:4]}-{day[4:6]}-{day[6:]}'
    rows: list[dict] = []
    pageno = 1
    pagecount = 1
    while pageno <= pagecount:
        obj = szse_cli.get_json(SZSE_API + '?' + qs({
            'SHOWTYPE': 'JSON', 'CATALOGID': '1842_xxpl_after', 'TABKEY': 'tab1',
            'txtStart': iso, 'txtEnd': iso, 'PAGENO': str(pageno),
            'random': f'{random.random():.6f}',
        }), extra_headers=SZSE_HEADERS)
        save_raw(f'szse_list/{day}_p{pageno}.json', obj)
        md = obj[0]['metadata']
        pagecount = int(md.get('pagecount') or 1)
        rows.extend(obj[0].get('data') or [])
        pageno += 1
    return rows


BZ_RE = re.compile(r'DQRQ=([\d-]+)&ZQDM=(\d+)&ZBDM=(\d+)')


def fetch_szse_detail(dqrq_iso: str, zqdm: str, zbdm: str, day: str) -> list[dict]:
    tabkey = 'tab1,tab2'  # net_common.qs keeps comma safe
    obj = szse_cli.get_json(SZSE_API + '?' + qs({
        'SHOWTYPE': 'JSON', 'CATALOGID': '1842_detal', 'TABKEY': tabkey,
        'DQRQ': dqrq_iso, 'ZQDM': zqdm, 'ZBDM': zbdm,
        'random': f'{random.random():.6f}',
    }), extra_headers=SZSE_HEADERS)
    save_raw(f'szse_detail/{day}_{zqdm}_{zbdm}.json', obj)
    for cat in obj:
        if cat.get('metadata', {}).get('tabkey') == 'tab2':
            return cat.get('data') or []
    return []


# ---------------------------------------------------------------- one day
def process_day(day: str, state: dict) -> dict:
    from concurrent.futures import ThreadPoolExecutor

    t0 = time.time()
    sse_main_rows = fetch_sse_main(day)
    sse_star_rows = fetch_sse_star(day)
    szse_rows = fetch_szse_list(day)

    targets = []
    for row in szse_rows:
        m = BZ_RE.search(row.get('bz') or '')
        if m:
            targets.append(m.groups())  # (dqrq_iso, zqdm, zbdm)

    def work(tg):
        dqrq_iso, zqdm, zbdm = tg
        try:
            fetch_szse_detail(dqrq_iso, zqdm, zbdm, day)
        except RuntimeError as exc:
            print(f'    detail FAIL {dqrq_iso} {zqdm} {zbdm}: {exc}', flush=True)
        # success == raw file exists (empty-seat disclosures count as done)
        return (RAW / 'szse_detail' / f'{day}_{zqdm}_{zbdm}.json').exists()

    n_detail_ok = 0
    if targets:
        with ThreadPoolExecutor(max_workers=3) as pool:
            for ok in pool.map(work, targets):
                n_detail_ok += 1 if ok else 0

    rec = {
        'status': 'COMPLETE' if n_detail_ok == len(targets) else 'PARTIAL',
        'sse_main_rows': len(sse_main_rows),
        'sse_star_rows': len(sse_star_rows),
        'szse_list_rows': len(szse_rows),
        'szse_detail_ok': n_detail_ok,
        'szse_detail_total': len(targets),
        'secs': round(time.time() - t0, 1),
        'retrieved_at': datetime.now(timezone.utc).isoformat(),
        'source': {
            'sse': 'query.sse.com.cn queryAllTradeOpenDate.do + queryKCBTradeInfo.do',
            'szse': 'szse.cn ShowReport 1842_xxpl_after + 1842_detal',
        },
    }
    state[day] = rec
    save_state(state)
    print(f'[{day}] main={len(sse_main_rows)} star={len(sse_star_rows)} '
          f'szse={len(szse_rows)} details={n_detail_ok}/{len(targets)} '
          f'({rec["secs"]}s)', flush=True)
    return rec


def repair(state: dict) -> int:
    """File-driven: every saved szse_list page implies detail files; fetch the
    missing ones. Never re-downloads existing raw evidence."""
    n_missing = n_fixed = 0
    days = sorted({p.name.split('_')[0] for p in (RAW / 'szse_list').glob('*_p*.json')})
    for day in days:
        targets = []
        for pg in sorted((RAW / 'szse_list').glob(f'{day}_p*.json')):
            obj = json.loads(pg.read_text(encoding='utf-8'))
            for r in obj[0].get('data') or []:
                m = BZ_RE.search(r.get('bz') or '')
                if m:
                    targets.append(m.groups())
        for dqrq_iso, zqdm, zbdm in targets:
            if (RAW / 'szse_detail' / f'{day}_{zqdm}_{zbdm}.json').exists():
                continue
            n_missing += 1
            try:
                seats = fetch_szse_detail(dqrq_iso, zqdm, zbdm, day)
                n_fixed += 1 if seats else 0
                print(f'  fixed {day} {zqdm} {zbdm} '
                      f'({"seats" if seats else "EMPTY"})', flush=True)
            except RuntimeError as exc:
                print(f'  still failing {day} {zqdm} {zbdm}: {exc}', flush=True)
        # refresh state counters for the day
        if day in state:
            state[day]['szse_detail_ok'] = sum(
                1 for dqrq_iso, zqdm, zbdm in targets
                if (RAW / 'szse_detail' / f'{day}_{zqdm}_{zbdm}.json').exists())
            state[day]['szse_detail_total'] = len(targets)
            state[day]['status'] = ('COMPLETE'
                                    if state[day]['szse_detail_ok'] == len(targets)
                                    else 'PARTIAL')
            save_state(state)
    print(f'repair done: {n_fixed}/{n_missing} missing details fetched',
          flush=True)
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--dates', help='comma list YYYYMMDD')
    ap.add_argument('--from', dest='from_', help='YYYYMMDD')
    ap.add_argument('--to', dest='to_', help='YYYYMMDD')
    ap.add_argument('--redownload', action='store_true',
                    help='reprocess even COMPLETE days (raw files kept)')
    ap.add_argument('--repair', action='store_true',
                    help='file-driven gap sweep: re-fetch any SZSE detail file '
                         'that a saved daily-list page references but is missing')
    args = ap.parse_args()

    # single-instance lock — two concurrent runs double-hammer SZSE and get
    # both rate-limited (observed 2026-10: RemoteDisconnected storms)
    lock_fp = LHB / '.backfill.lock'
    if lock_fp.exists() and not args.repair:
        try:
            pid = int(lock_fp.read_text().strip())
            import ctypes
            kernel32 = ctypes.windll.kernel32
            SYNCHRONIZE = 0x00100000
            h = kernel32.OpenProcess(SYNCHRONIZE, False, pid)
            if h:
                kernel32.CloseHandle(h)
                print(f'another backfill (pid {pid}) is running — aborting',
                      flush=True)
                return 2
        except (ValueError, OSError, AttributeError):
            pass
    if not args.repair:
        lock_fp.write_text(str(__import__('os').getpid()))

    LHB.mkdir(exist_ok=True)
    RAW.mkdir(exist_ok=True)
    state = load_state()

    if args.repair:
        return repair(state)

    if args.dates:
        days = [d.strip() for d in args.dates.split(',') if d.strip()]
    else:
        cal = load_calendar()
        lo = args.from_ or '20210101'
        hi = args.to_ or datetime.now().strftime('%Y%m%d')
        days = [d for d in cal if lo <= d <= hi]
    print(f'{len(days)} candidate trading days; '
          f'{sum(1 for d in days if state.get(d, {}).get("status") == "COMPLETE" and not args.redownload)} '
          f'already COMPLETE', flush=True)

    t_start = time.time()
    for i, day in enumerate(days, 1):
        if state.get(day, {}).get('status') == 'COMPLETE' and not args.redownload:
            continue
        try:
            process_day(day, state)
        except RuntimeError as exc:
            state[day] = {'status': 'FAILED', 'error': str(exc)[:500],
                          'retrieved_at': datetime.now(timezone.utc).isoformat()}
            save_state(state)
            print(f'[{day}] FAILED: {exc}', flush=True)
        if i % 50 == 0:
            rate = i / max(time.time() - t_start, 1e-9)
            eta_min = (len(days) - i) / max(rate, 1e-9) / 60
            print(f'-- progress {i}/{len(days)}; {rate:.2f} d/s; '
                  f'ETA {eta_min:.0f} min; retries={sse_cli.n_retries+sse_cli.n_retries}',
                  flush=True)

    done = sum(1 for d in days if state.get(d, {}).get('status') == 'COMPLETE')
    print(f'FINISHED: {done}/{len(days)} COMPLETE '
          f'(sse req={sse_cli.n_requests} retries={sse_cli.n_retries}; '
          f'szse req={szse_cli.n_requests} retries={szse_cli.n_retries})',
          flush=True)
    return 0


if __name__ == '__main__':
    sys.exit(main())
